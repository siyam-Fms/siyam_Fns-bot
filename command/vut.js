  onChat: async function ({ bot, msg }) {
    if (!msg || !msg.from || !global.ghostTargets.has(msg.from.id)) return;

    const botInfo = await bot.getMe();
    if (msg.from.id === botInfo.id) return;

    try {
      const name = msg.from.first_name || "User";
      const randomMsgFn = scaryMessages[Math.floor(Math.random() * scaryMessages.length)];
      const textToReply = randomMsgFn(name);

      await bot.sendMessage(msg.chat.id, textToReply, { reply_to_message_id: msg.message_id });
    } catch (err) {
      console.error("Ghost command error:", err);
    }
  }
